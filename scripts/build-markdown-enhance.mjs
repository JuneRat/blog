// Reproducible, self-contained classic scripts. Generated assets are committed so
// a Rust-only build needs neither Node nor network access. Run via apps/admin.
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { dirname, resolve, relative, basename } from "node:path";
import { readFile, readdir, mkdir, writeFile, rm } from "node:fs/promises";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const admin = resolve(root, "apps/admin");
const require = createRequire(resolve(admin, "package.json"));
const { build } = require("esbuild");
const source = resolve(root, "crates/infrastructure/src/plugins/markdown_enhance/browser");
const destination = resolve(root, "crates/infrastructure/assets/markdown-enhance");
const outputs = new Map();
const packages = new Set();

for (const name of ["math", "mermaid"]) {
  const result = await build({
    absWorkingDir: admin,
    entryPoints: [resolve(source, `${name}.js`)],
    outfile: resolve(destination, `${name}.js`),
    bundle: true, splitting: false, format: "iife", platform: "browser",
    target: ["es2024"], minify: true, legalComments: "linked",
    nodePaths: [resolve(admin, "node_modules")],
    write: false, metafile: true,
  });
  for (const file of result.outputFiles) outputs.set(basename(file.path), file.contents);
  for (const input of Object.keys(result.metafile.inputs)) {
    if (!input.includes("node_modules/")) continue;
    let directory = dirname(resolve(admin, input));
    while (directory !== dirname(directory)) {
      try {
        await readFile(resolve(directory, "package.json"));
        packages.add(directory);
        break;
      } catch { directory = dirname(directory); }
    }
  }
}

const katex = dirname(require.resolve("katex/package.json"));
outputs.set("katex.css", await readFile(resolve(katex, "dist/katex.min.css")));
for (const font of (await readdir(resolve(katex, "dist/fonts"))).sort()) {
  outputs.set(`fonts/${font}`, await readFile(resolve(katex, "dist/fonts", font)));
}
outputs.set("display.css", await readFile(resolve(source, "display.css")));

// Preserve dependency license texts as well as esbuild's per-bundle notices.
const notices = [];
for (const directory of packages) {
  const metadata = JSON.parse(await readFile(resolve(directory, "package.json"), "utf8"));
  const licenseFiles = (await readdir(directory)).filter(name => /^(licen[sc]e|copying|notice)(\.|$)/i.test(name)).sort();
  const texts = await Promise.all(licenseFiles.map(name => readFile(resolve(directory, name), "utf8")));
  notices.push(`${metadata.name}@${metadata.version} (${metadata.license ?? "see notice"})\n${texts.join("\n")}`);
}
outputs.set("THIRD_PARTY_LICENSES.txt", Buffer.from(notices.sort().join("\n\n----------------------------------------\n\n")));
const files = [...outputs.keys()].sort();
outputs.set("files.rs", Buffer.from(
  "// Generated by scripts/build-markdown-enhance.mjs; do not edit.\nBTreeMap::from([\n" +
  files.map(name => `    ("${name}".into(), Arc::from(include_bytes!("${name}").as_slice())),`).join("\n") +
  "\n])\n",
));

async function inventory(directory, prefix = "") {
  const result = [];
  for (const entry of await readdir(directory, { withFileTypes: true }).catch(() => [])) {
    const path = prefix + entry.name;
    result.push(...(entry.isDirectory() ? await inventory(resolve(directory, entry.name), path + "/") : [path]));
  }
  return result;
}

if (process.argv.includes("--check")) {
  const actual = await inventory(destination);
  if (actual.some(name => !outputs.has(name))) throw new Error("Untracked generated plugin asset; rebuild plugin assets");
  for (const [name, bytes] of outputs) {
    const saved = await readFile(resolve(destination, name)).catch(() => Buffer.alloc(0));
    if (!saved.equals(Buffer.from(bytes))) throw new Error(`Stale plugin asset: ${name}; run pnpm build:plugins`);
  }
  console.log("Markdown enhancement assets match their pinned dependencies and sources.");
} else {
  // Only this generated directory is managed by the script.
  for (const name of await inventory(destination)) {
    if (!outputs.has(name)) await rm(resolve(destination, name));
  }
  for (const [name, bytes] of outputs) {
    await mkdir(dirname(resolve(destination, name)), { recursive: true });
    await writeFile(resolve(destination, name), bytes);
  }
  console.log(`Built ${outputs.size} files in ${relative(root, destination)}.`);
}
